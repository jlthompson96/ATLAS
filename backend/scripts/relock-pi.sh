#!/usr/bin/env bash
# Build a per-service Pi runtime lock for Linux aarch64 / CPython 3.13 (contracts/services.md section 6).
#
# usage: scripts/relock-pi.sh <extra> <pkg==ver>...
#   e.g. scripts/relock-pi.sh audit cryptography==47.0.0 cffi==2.1.1 pycparser==3.12
#
# The pins come from the reviewed dev lock (requirements-dev.lock). For each pin this downloads the manylinux
# aarch64 wheel (binary only, no sdists, no dependency resolution) and records its SHA-256, so the Pi installs
# with `pip install --require-hashes --only-binary=:all:`. Re-run inside the ARM64 Debian VM to cross-check
# (the hashes must be identical). Review the diff before committing.
set -euo pipefail
cd "$(dirname "$0")/.."

extra="${1:?extra name}"
shift
[ "$#" -ge 1 ] || { echo "no pins given" >&2; exit 2; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
python3 -m venv "$tmp/venv"
mkdir "$tmp/wheels"
out="requirements-${extra}.lock"
{
  echo "# Pi runtime lock for the '${extra}' extra. Linux aarch64, CPython 3.13, binary wheels only."
  echo "# Generated by scripts/relock-pi.sh; install with: pip install --require-hashes --only-binary=:all: -r $out"
} >"$out"
for pin in "$@"; do
  "$tmp/venv/bin/pip" download --quiet --no-deps --only-binary=:all: \
    --platform manylinux2014_aarch64 --platform manylinux_2_17_aarch64 --platform manylinux_2_28_aarch64 \
    --python-version 3.13 --implementation cp --abi cp313 --abi abi3 --abi none \
    -d "$tmp/wheels" "$pin"
done
for f in "$tmp"/wheels/*.whl; do
  base="$(basename "$f")"
  name="${base%%-*}"
  rest="${base#*-}"
  version="${rest%%-*}"
  hash="$(shasum -a 256 "$f" | cut -d' ' -f1)"
  printf '%s==%s \\\n    --hash=sha256:%s\n' "$(echo "$name" | tr '_' '-' | tr '[:upper:]' '[:lower:]')" "$version" "$hash" >>"$out"
done
echo "Wrote $out"
